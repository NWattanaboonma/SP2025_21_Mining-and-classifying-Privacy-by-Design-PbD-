def get_session():
    """Creates a robust session with retry logic."""
    retry_strategy = Retry(
        total=5,
        backoff_factor=2,
        status_forcelist=[500, 502, 503, 504],
        allowed_methods=["GET", "HEAD"]
    )
    adapter = HTTPAdapter(max_retries=retry_strategy)
    session = requests.Session()
    session.mount("https://", adapter)
    session.headers.update({
        "Authorization": f"token {GITHUB_TOKEN}",
        "Accept": "application/vnd.github.v3+json"
    })
    return session

def log_message(message):
    """Prints to console and appends to log file."""
    print(message)
    try:
        with open(LOG_FILE, "a", encoding="utf-8") as f:
            f.write(str(message) + "\n")
    except Exception:
        pass

def get_processed_repos(output_file, tracking_file=None):
    """Checks the output file and tracking file to see which repos are already fully scraped."""
    processed = set()
    
    # 1. Check CSV (Repositories that had issues)
    if os.path.exists(output_file):
        try:
            # We read only the 'Repo_Name' column to save memory
            df = pd.read_csv(output_file, usecols=["Repo_Name"])
            processed.update(df["Repo_Name"].unique())
        except Exception as e:
            log_message(f"⚠️ Could not read existing progress from CSV: {e}")

    # 2. Check Tracking File (Repositories that were processed but had 0 issues)
    if tracking_file and os.path.exists(tracking_file):
        try:
            with open(tracking_file, "r", encoding="utf-8") as f:
                for line in f:
                    processed.add(line.strip())
        except Exception as e:
            log_message(f"⚠️ Could not read existing progress from tracking file: {e}")
            
    return processed

