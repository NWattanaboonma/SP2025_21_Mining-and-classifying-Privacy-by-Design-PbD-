def fetch_issues_for_repo(session, repo_full_name):
    """
    Fetches all issues for a specific repository.
    Handles pagination and filters out Pull Requests.
    """
    issues_data = []
    page = 1
    url = f"https://api.github.com/repos/{repo_full_name}/issues"
    
    log_message(f"   > Fetching: {repo_full_name} ...")

    while True:
        params = {
            "state": STATE,
            "per_page": PER_PAGE,
            "page": page,
            "sort": "created",
            "direction": "asc"
        }

        try:
            response = session.get(url, params=params)

            # --- Rate Limit Handling ---
            if response.status_code == 403:
                remaining = response.headers.get('X-RateLimit-Remaining')
                if remaining is not None and int(remaining) == 0:
                    reset_time = int(response.headers.get('X-RateLimit-Reset', time.time() + 60))
                    sleep_time = max(1, reset_time - int(time.time())) + 5
                    log_message(f"      ⚠️ Rate Limit Exceeded! Sleeping {sleep_time}s...")
                    time.sleep(sleep_time)
                    continue 
                
                if "secondary rate limit" in response.text.lower():
                    log_message("      ⚠️ Secondary Rate Limit! Sleeping 60s...")
                    time.sleep(60)
                    continue

                log_message(f"      ❌ Access Forbidden (403): {response.text}")
                return None
            
            if response.status_code != 200:
                log_message(f"      ❌ Error {response.status_code}: {response.text}")
                return None  # Return None to indicate failure (don't save partial data)

            items = response.json()
            if not items:
                break # No more pages

            for item in items:
                # GitHub API returns PRs as issues. We usually want to filter them out.
                if "pull_request" in item:
                    continue

                # Flatten labels into a string
                labels = [label['name'] for label in item.get('labels', [])]

                issues_data.append({
                    "Repo_Name": repo_full_name,
                    "Issue_ID": item['id'],
                    "Number": item['number'],
                    "Title": item['title'],
                    "State": item['state'],
                    "Author": item['user']['login'] if item.get('user') else "N/A",
                    "Assignees": ", ".join([u['login'] for u in item.get('assignees', [])]),
                    "Milestone": item['milestone']['title'] if item.get('milestone') else "N/A",
                    "Locked": item.get('locked', False),
                    "Created_At": item['created_at'],
                    "Closed_At": item['closed_at'],
                    "Updated_At": item['updated_at'],
                    "Comments_Count": item['comments'],
                    "Labels": ", ".join(labels),
                    "Body": item['body'], # Warning: Can be very long
                    "URL": item['html_url']
                })
            
            # Progress indicator for large repos
            if page % 5 == 0:
                log_message(f"      ... Processed Page {page} ({len(issues_data)} issues found so far)")

            page += 1
            time.sleep(0.5) # Politeness delay between pages

        except Exception as e:
            log_message(f"      ❌ Exception on page {page}: {e}")
            return None  # Return None to indicate failure

    return issues_data

