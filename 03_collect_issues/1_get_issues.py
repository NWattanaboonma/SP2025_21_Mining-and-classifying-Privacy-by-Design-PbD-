def convert_csv_to_json(csv_filename):
    """Converts the raw CSV to a JSON file."""
    if not os.path.exists(csv_filename):
        return

    json_filename = csv_filename.replace(".csv", ".json")
    log_message(f"   📊 Converting to JSON: {json_filename}...")

    try:
        df = pd.read_csv(csv_filename, low_memory=False)
        df.to_json(json_filename, orient='records', indent=4, force_ascii=False)
        log_message(f"   ✅ Saved JSON file.")
    except Exception as e:
        log_message(f"   ❌ Error converting to JSON: {e}")

