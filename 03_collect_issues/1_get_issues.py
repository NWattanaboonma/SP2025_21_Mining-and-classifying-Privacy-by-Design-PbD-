# 4. MAIN EXECUTION
# ==========================================
if __name__ == "__main__":
    if not GITHUB_TOKEN:
        log_message("❌ Error: GITHUB_TOKEN is missing.")
        exit()

    if not os.path.exists(INPUT_REPO_FILE):
        log_message(f"⚠️  Default input file '{INPUT_REPO_FILE}' not found.")
        
        # Auto-detect potential files
        potential_files = []
        for root, dirs, files in os.walk("."):
            for file in files:
                if file.startswith("found_repositories") and file.endswith(".csv"):
                    potential_files.append(os.path.join(root, file))
        
        if potential_files:
            print("\n📂 Found potential repository files in directory tree:")
            for i, f in enumerate(potential_files):
                print(f"   {i+1}: {f}")
            
            choice = input("\nSelect a file number or enter a filename: ").strip()
            
            if choice.isdigit() and 1 <= int(choice) <= len(potential_files):
                INPUT_REPO_FILE = potential_files[int(choice)-1]
            else:
                INPUT_REPO_FILE = choice.replace('"', '').replace("'", "")
        else:
            INPUT_REPO_FILE = input("\n📝 Please enter the repository CSV filename: ").strip().replace('"', '').replace("'", "")

        if not os.path.exists(INPUT_REPO_FILE):
            log_message(f"❌ Error: File '{INPUT_REPO_FILE}' not found.")
            exit()

    # 1. Load Repositories to Scrape
    log_message(f"📂 Loading repositories from {INPUT_REPO_FILE}...")
    try:
        repo_df = pd.read_csv(INPUT_REPO_FILE, low_memory=False)
        log_message(f"📊 Found {len(repo_df)} repositories.")
    except KeyError:
        log_message("❌ Error: Column 'Repo_Name' not found in input CSV.")
        exit()

    # Mode Selection
    print("\n--- Execution Mode ---")
    print("0: Restart (⚠️  WARNING: Clears all progress for these domains)")
    print("1: Verify/Fill Gaps (Checks all repos, skips if already processed)")
    print("3: Resume (Continues from the last processed repository)")
    mode = input("Select Mode (0, 1, or 3): ").strip()
    if mode not in ['0', '1', '3']: mode = '1'

    # Check for Domain column
    if 'Domain' not in repo_df.columns:
        log_message("⚠️ Warning: 'Domain' column not found. Treating all as 'Uncategorized'.")
        repo_df['Domain'] = 'Uncategorized'

    # Group by Domain
    grouped = repo_df.groupby('Domain')

    session = get_session()

    for domain, group in grouped:
        # Create safe filename for domain
        safe_domain = "".join([c for c in str(domain) if c.isalnum() or c in (' ', '-', '_')]).strip().replace(' ', '_')
        domain_output_file = f"issues_{safe_domain}.csv"
        domain_tracking_file = f"processed_{safe_domain}.txt"
        
        log_message(f"\n🌍 Processing Domain: {domain} (Output: {domain_output_file})")
        
        target_repos = group['Repo_Name'].unique().tolist()
        start_index = 0
        processed_repos = set()

        if mode == '0':
            # Restart: Clear files
            if os.path.exists(domain_output_file):
                os.remove(domain_output_file)
                log_message(f"   🗑️  Deleted {domain_output_file}")
            if os.path.exists(domain_tracking_file):
                os.remove(domain_tracking_file)
                log_message(f"   🗑️  Deleted {domain_tracking_file}")
            json_file = domain_output_file.replace(".csv", ".json")
            if os.path.exists(json_file):
                os.remove(json_file)
        else:
            # Load existing progress
            processed_repos = get_processed_repos(domain_output_file, domain_tracking_file)
            
            if mode == '3':
                # Resume: Find last processed repo
                last_repo = None
                # Check tracking file first
                if os.path.exists(domain_tracking_file):
                    try:
                        with open(domain_tracking_file, "r", encoding="utf-8") as f:
                            lines = [l.strip() for l in f if l.strip()]
                            if lines: last_repo = lines[-1]
                    except: pass
                
                # If not found, check CSV
                if not last_repo and os.path.exists(domain_output_file):
                    try:
                        df_tmp = pd.read_csv(domain_output_file, usecols=["Repo_Name"])
                        if not df_tmp.empty: last_repo = df_tmp.iloc[-1]["Repo_Name"]
                    except: pass
                
                if last_repo and last_repo in target_repos:
                    start_index = target_repos.index(last_repo) + 1
                    log_message(f"   ⏩ Resuming from index {start_index} (after '{last_repo}')")
                else:
                    log_message("   ℹ️  No resume point found. Starting from beginning.")
        
        log_message(f"   🔄 Status: {len(processed_repos)}/{len(target_repos)} repositories marked as done.")

        for i in range(start_index, len(target_repos)):
            repo_name = target_repos[i]
            if repo_name in processed_repos:
                continue 

            log_message(f"   [{i+1}/{len(target_repos)}] Processing: {repo_name}")
            
            issues = fetch_issues_for_repo(session, repo_name)
            
            if issues is None:
                log_message(f"      ❌ Failed to complete {repo_name}. Will retry next run.")
                continue

            if issues: # If list is not empty
                # Add Domain column to issue data
                for issue in issues:
                    issue['Domain'] = domain

                df = pd.DataFrame(issues)
                
                # Append to Domain CSV
                header = not os.path.exists(domain_output_file)
                df.to_csv(domain_output_file, mode='a', header=header, index=False, encoding='utf-8-sig')
                log_message(f"      ✅ Saved {len(issues)} issues.")
            else:
                log_message(f"      ⚠️ No issues found.")

            # Mark as processed in tracking file (so we don't retry it if 0 issues found)
            try:
                with open(domain_tracking_file, "a", encoding="utf-8") as f:
                    f.write(f"{repo_name}\n")
            except Exception as e:
                log_message(f"      ⚠️ Failed to update tracking file: {e}")

            time.sleep(1)

        # After domain is finished, convert to JSON
        convert_csv_to_json(domain_output_file)

    log_message("\n🎉 All domains processed!")